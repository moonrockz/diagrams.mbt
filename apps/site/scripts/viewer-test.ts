// Exercise the shared viewport assets independently from a site build.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const js = await readFile('pkgs/diagrams-animated/assets/viewer.js', 'utf8');
const css = await readFile('pkgs/diagrams-animated/assets/viewer.css', 'utf8');
const image = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 400"><rect width="1000" height="400" fill="#fafafa"/><path d="M10 200 Q500 10 990 200" fill="none" stroke="blue"/><text x="400" y="200">Complete diagram</text></svg>';
const viewer = (id: string, skin = '') => `<section class="diagram-viewer" data-diagram-viewer id="${id}" style="${skin}"><div class="diagram-viewer__viewport"><div class="diagram-viewer__content">${image}</div></div></section>`;
const html = `<!doctype html><meta name="viewport" content="width=device-width"><style>body{margin:0}.diagram-viewer{padding:8px;box-sizing:border-box} ${css}</style><a href="#after">Before</a>${viewer('one', '--diagram-viewer-accent: rgb(200, 30, 90); --diagram-viewer-surface: rgb(240, 220, 230); --diagram-viewer-control-radius: 12px')}${viewer('two')}<button id="after">After</button><script>Element.prototype.requestFullscreen = async function(){throw new Error('Denied')};</script><script>${js}</script>`;
const browser = await chromium.launch();
const errors: string[] = [], requests: string[] = [];
try {
  for (const width of [360, 768, 1440]) for (const theme of ['light', 'dark'] as const) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, colorScheme: theme });
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => { requests.push(route.request().url()); return route.abort(); });
    await page.setContent(html);
    const one = page.locator('#one'), two = page.locator('#two'), viewport = one.locator('.diagram-viewer__viewport');
    await one.locator('[aria-label="Zoom in"]').waitFor();
    assert.equal(await one.getAttribute('data-viewer-resolved-theme'), theme);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await one.locator('button').evaluateAll(items => items.every(item => item.getBoundingClientRect().width >= 44 && item.getBoundingClientRect().height >= 44)), true);
    const fit = await viewport.locator('svg').boundingBox(), frame = await viewport.boundingBox();
    assert.ok(fit && frame && fit.x >= frame.x && fit.x + fit.width <= frame.x + frame.width + 1 && fit.y >= frame.y && fit.y + fit.height <= frame.y + frame.height + 1);
    await one.locator('[aria-label="Zoom in"]').click();
    assert.equal(await viewport.getAttribute('data-viewer-scale'), '1.25');
    assert.equal(await two.locator('.diagram-viewer__viewport').getAttribute('data-viewer-scale'), '1');
    const content = viewport.locator('.diagram-viewer__content');
    const before = await content.getAttribute('style');
    await viewport.focus(); await page.keyboard.press('ArrowLeft');
    assert.notEqual(await content.getAttribute('style'), before);
    const panned = await content.getAttribute('style');
    await one.locator('[aria-label="Zoom in"]').focus(); await page.keyboard.press('ArrowLeft');
    assert.equal(await content.getAttribute('style'), panned);
    const bounds = await viewport.boundingBox(); assert.ok(bounds);
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 30, bounds.y + bounds.height / 2 + 20); await page.mouse.up();
    assert.notEqual(await content.getAttribute('style'), panned);
    await one.locator('[aria-label="Fit diagram"]').click();
    assert.equal(await viewport.getAttribute('data-viewer-scale'), '1');
    for (let i = 0; i < 15; i++) { const button = one.locator('[aria-label="Zoom in"]'); if (await button.isEnabled()) await button.click(); }
    assert.equal(await viewport.getAttribute('data-viewer-scale'), '8');
    assert.equal(await one.locator('[aria-label="Zoom in"]').isDisabled(), true);
    for (let i = 0; i < 20; i++) { const button = one.locator('[aria-label="Zoom out"]'); if (await button.isEnabled()) await button.click(); }
    assert.equal(await viewport.getAttribute('data-viewer-scale'), '0.25');
    assert.equal(await one.locator('[aria-label="Zoom out"]').isDisabled(), true);
    await one.locator('[aria-label="Fullscreen"]').click();
    await page.getByRole('dialog').waitFor();
    assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
    assert.equal(await two.evaluate(element => (element as HTMLElement).inert), true);
    assert.equal(await viewport.evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(240, 220, 230)');
    await page.keyboard.press('Tab');
    assert.equal(await one.locator('[aria-label="Zoom out"]').evaluate(element => element === document.activeElement), false); // disabled at minimum
    assert.equal(await one.locator('[aria-label="Zoom in"]').evaluate(element => element === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    assert.equal(await two.evaluate(element => (element as HTMLElement).inert), false);
    assert.equal(await one.locator('[aria-label="Fullscreen"]').evaluate(element => element === document.activeElement), true);
    await one.evaluate(element => element.setAttribute('data-viewer-theme', 'light'));
    await page.waitForFunction(() => document.querySelector('#one')?.getAttribute('data-viewer-resolved-theme') === 'light');
    await page.emulateMedia({ media: 'print' });
    assert.equal(await one.locator('.diagram-viewer__toolbar').isVisible(), false);
    assert.equal(await content.evaluate(element => getComputedStyle(element).transform), 'none');
    await page.close();
  }
  const noScript = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 360, height: 800 } });
  await noScript.setContent(html);
  assert.equal(await noScript.locator('.diagram-viewer__toolbar').count(), 0);
  assert.equal(await noScript.locator('svg').first().isVisible(), true);
  await noScript.close();
  const scrolled = await browser.newPage({ viewport: { width: 360, height: 800 } });
  await scrolled.setContent(html.replace('<button id="after">', '<div style="height:2000px"></div><button id="after">'));
  const lastFullscreen = scrolled.locator('#two [aria-label="Fullscreen"]');
  await lastFullscreen.scrollIntoViewIfNeeded();
  const priorScroll = await scrolled.evaluate(() => scrollY);
  await lastFullscreen.click(); await scrolled.getByRole('dialog').waitFor();
  await scrolled.keyboard.press('Escape');
  assert.equal(await scrolled.evaluate(() => scrollY), priorScroll);
  await scrolled.close();
  const native = await browser.newPage();
  await native.setContent(html.replace("Element.prototype.requestFullscreen = async function(){throw new Error('Denied')};", ''));
  await native.locator('#one [aria-label="Fullscreen"]').click();
  await native.waitForFunction(() => document.fullscreenElement !== null);
  assert.equal(await native.evaluate(() => document.fullscreenElement?.classList.contains('diagram-viewer__viewport')), true);
  await native.evaluate(() => document.exitFullscreen());
  await native.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Fullscreen');
  await native.close();
  const touch = await browser.newPage({ hasTouch: true, viewport: { width: 360, height: 800 } });
  await touch.setContent(html);
  await touch.locator('#one [aria-label="Zoom in"]').tap();
  const target = touch.locator('#one .diagram-viewer__content');
  const beforeTouch = await target.getAttribute('style');
  const cdp = await touch.context().newCDPSession(touch);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 160, y: 200 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 190, y: 220 }] });
  assert.notEqual(await target.getAttribute('style'), beforeTouch);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  const afterCancel = await target.getAttribute('style');
  await touch.mouse.move(100, 100);
  assert.equal(await target.getAttribute('style'), afterCancel);
  await touch.close();
  const storage = await browser.newPage({ colorScheme: 'light' });
  await storage.route('https://viewer.test/', route => route.fulfill({ contentType: 'text/html', body: html.replace('<script>Element.prototype', '<script>localStorage.setItem("site-theme", "dark");Element.prototype') }));
  await storage.goto('https://viewer.test/');
  assert.equal(await storage.locator('#one').getAttribute('data-viewer-resolved-theme'), 'dark');
  await storage.evaluate(() => { localStorage.setItem('site-theme', 'light'); document.documentElement.dataset.theme = 'light'; });
  await storage.waitForFunction(() => document.querySelector('#one')?.getAttribute('data-viewer-resolved-theme') === 'light');
  await storage.locator('#one').evaluate(element => element.setAttribute('data-viewer-theme', 'system'));
  await storage.emulateMedia({ colorScheme: 'dark' });
  await storage.waitForFunction(() => document.querySelector('#one')?.getAttribute('data-viewer-resolved-theme') === 'dark');
  await storage.close();
  assert.deepEqual(errors, []); assert.deepEqual(requests, []);
  console.log('Shared viewport: responsive themes, stored/explicit/system preference, fit, bounded zoom, mouse/touch/keyboard pan, pointer cancellation, native/modal fullscreen, focus/scroll/skin restoration, isolation, print and no-script passed.');
} finally { await browser.close(); }
